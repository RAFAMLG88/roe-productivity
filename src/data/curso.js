export const FUTURAS = []

export function semanaAtual(progresso) {
  // Devolve o número da primeira semana ainda não concluída (1..48).
  const concluidas = new Set((progresso || []).filter((p) => p.concluida).map((p) => p.semana))
  for (let n = 1; n <= 48; n++) {
    if (!concluidas.has(n)) return n
  }
  return 48
}
